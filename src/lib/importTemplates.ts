/** Имена файлов при скачивании */
export function templateFilename(entity: ImportEntity): string {
  return `scoresbox-import-${entity}.csv`;
}

/**
 * CSV-шаблон: заголовок + строки-примеры.
 * Разделитель «;» (стандарт русского Excel), перевод строки CRLF.
 * BOM добавляется на уровне HTTP-ответа (Excel-совместимость).
 */
export function buildTemplateCsv(entity: ImportEntity): string {
  const spec = IMPORT_SPECS[entity];
  const esc = (v: string) => (v.includes(";") || v.includes('"') || v.includes("\n") ? `"${v.replace(/"/g, '""')}"` : v);
  const header = spec.fields.map((f) => esc(f.name)).join(";");
  const rows = spec.exampleRows.map((r) => r.map(esc).join(";"));
  return [header, ...rows].join("\r\n") + "\r\n";
}

/**
 * Текстовый пример для вставки в поле ввода (кнопка «Пример в поле»):
 * то же содержимое, что и в скачиваемом шаблоне.
 */
export function templateText(entity: ImportEntity): string {
  return buildTemplateCsv(entity).trim();
}

