// ============================================================
// CSV-шаблоны массового импорта — единый источник правды.
//
// Используется:
//  • API /api/admin/import/template — скачивание CSV (Excel-совместимо:
//    BOM + разделитель «;» + CRLF);
//  • ImportPanel — кнопка «Скачать шаблон», таблица колонок в подсказке
//    и текстовые примеры в поле ввода.
//
// Для каждой сущности: список колонок (обязательность, формат, пример)
// и строки-примеры, демонстрирующие, что кладётся в ОДНУ ячейку,
// а что — в разные (ФИО — три колонки; несколько ролей — одна ячейка
// через запятую).
// ============================================================

export type ImportEntity = "players" | "persons" | "teams" | "stadiums" | "clubs";

export interface ImportFieldSpec {
  /** Название колонки (как в заголовке CSV) */
  name: string;
  /** Обязательна ли колонка/ячейка */
  required: boolean;
  /** Формат значения — для подсказки */
  format: string;
  /** Пример значения — для подсказки и строки-примера */
  example: string;
}

export interface ImportEntitySpec {
  /** Ключ сущности (совпадает с entity в /api/admin/import) */
  id: ImportEntity;
  /** Человеческое название вкладки */
  label: string;
  /** Что создаётся и по какому ключу ищется дубль */
  summary: string;
  /** Колонки */
  fields: ImportFieldSpec[];
  /** Строки-примеры для шаблона (значения по полям fields, по порядку) */
  exampleRows: string[][];
}

