## 4. «Штаб на матч» — играющий сотрудник (главная фича)

Кейс юзера: «игрок является и игроком, и начальником команды, и
директором — где закладывать роли?». Роль в заявке одна (игрок ИЛИ
сотрудник), поэтому совмещение сделано на уровне матча:

- редактор протокола → вкладка «Состав» → блок **«+ В штаб на этот
  матч»**: выберите человека из заявки (в т.ч. ИГРОКА) и должность —
  «Начальник команды» (новая роль), «Помощник тренера», «Тренер»,
  «Тренер вратарей», «Администратор», «Директор», «Врач»…;
- игрок с должностью — «играющий сотрудник»: остаётся в составе
  (номер, старт/запас как обычно) И появляется в секции «Штаб»
  публичной страницы матча с подписью должности; в списке игроков
  редактора — жёлтая пометка должности;
- должность заявки-штаба (тренер/администратор из заявки) можно
  ПЕРЕОПРЕДЕЛИТЬ на матч селектором в строке — заявка не меняется;
- убрать должность — крестик (игрок остаётся в составе);
- должность живёт в протоколе матча: на следующий матч назначается
  заново (или другому человеку);
- судейская бригада матча (судьи, помощники, инспектор, делегат,
  врач) — как и раньше, на вкладке «Бригада».

API: `staffRoles: [{ personId, role }]` в action=«lineup»; мусорный
код роли или должность человеку вне состава → 422 с понятным текстом.

