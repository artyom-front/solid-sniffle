## 6. Что проверить на проде

1. страница матча: вкладка «Протокол» — без числа событий;
2. страница «Дисциплина» лиги: подсказки про карточки не видно,
   баны/история на месте;
3. панель «Заявки»: подсказка у переключателя «трансфер» — «действует
   только внутри сезона этого турнира»;
4. редактор протокола → «Состав»: блок «+ В штаб на этот матч» —
   добавьте игрока как «Начальник команды», подайте состав →
   публичная страница: игрок и в составе с номером, и в «Штабе»;
5. POST с мусорной ролью (напрямую API) → 422 «не распознана».

