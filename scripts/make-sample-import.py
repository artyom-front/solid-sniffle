#!/usr/bin/env python3
"""Образцовый CSV массового импорта игроков (UTF-8 + BOM, «;», CRLF)
с реальными строками пользователя (первые 5 из его таблицы).
Кладётся в public/download/ — скачивается по preview-ссылке.
"""

rows = [
    ["Фамилия", "Имя", "Отчество", "ДатаРождения", "Позиция", "Номер", "Роль"],
    ["Артемьев", "Демьян", "Олегович", "22.07.1990", "Нападающий", "1", "Игрок"],
    ["Баторшин", "Владимир", "Олегович", "23.07.1990", "Нападающий", "1", "Игрок"],
    ["Баторшин", "Денис", "Олегович", "24.07.1990", "Нападающий", "1", "Игрок"],
    ["Бельцов", "Александр", "Олегович", "25.07.1990", "Нападающий", "1", "Игрок"],
    ["Глухарев", "Антон", "Олегович", "26.07.1990", "Нападающий", "1", "Игрок"],
]

lines = [";".join(r) for r in rows]
csv = "\r\n".join(lines) + "\r\n"

# BOM (EF BB BF) — Excel открывает без танцев, наш парсер BOM срезает
data = b"\xef\xbb\xbf" + csv.encode("utf-8")

out = "public/download/players-example-utf8.csv"
with open(out, "wb") as f:
    f.write(data)

# самопроверка: файл читается как UTF-8, структура колонок правильная
text = data.decode("utf-8-sig")
assert text.splitlines()[0] == "Фамилия;Имя;Отчество;ДатаРождения;Позиция;Номер;Роль"
assert len(text.rstrip("\r\n").split("\r\n")) == 6
print(f"OK: {out}, {len(data)} байт, 6 строк (заголовок + 5 игроков)")
